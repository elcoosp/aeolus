/// The runtime-tier table over the shadcn light+dark source.
fn runtime_table() -> TokenTable {
    let source = ThemeSource::shadcn_dark().expect("embedded palettes parse");
    TokenTable::runtime(&source).expect("default-seeded source builds")
}

/// The first declaration for `prop` in the base layer of `compiled`.
fn base_decl(compiled: &aeolus_compile::Compiled, prop: Prop) -> Val {
    let layer = compiled
        .program
        .layers
        .iter()
        .find(|layer| layer.cond == aeolus_ir::Cond::Base)
        .expect("the base layer exists");
    layer
        .decls
        .iter()
        .find(|decl| decl.prop == prop)
        .expect("the longhand is set")
        .val
}

/// The one diagnostic the battery expects — `compile` reports must be
/// singular for these single-class strings.
fn one_diagnostic(compiled: &aeolus_compile::Compiled) -> &DiagnosticKind {
    assert_eq!(
        compiled.diagnostics.len(),
        1,
        "exactly one report: {:?}",
        compiled.diagnostics
    );
    &compiled.diagnostics[0].kind
}

