#[test]
fn a_paren_var_shorthand_is_the_var_form() {
    // v4.1's `(--var)` shorthand: `w-(--mine)` is `w-[var(--mine)]`.
    let table = runtime_table();
    let source = ThemeSource::shadcn_dark().expect("embedded palettes parse");
    let _ = source;
    let compiled =
        compile_theme("w-(--color-primary)", &table, &Config::default()).expect("compiles");
    // `primary` is a COLOUR token; a width slot refuses it typed — but
    // the REFUSAL is the value-class gate's, not a var-form miss: the
    // same string with a colour root lowers.
    assert!(matches!(
        compiled.diagnostics.first().map(|d| &d.kind),
        Some(DiagnosticKind::UnsupportedValue { .. })
    ));
    let via_paren =
        compile_theme("bg-(--color-primary)", &table, &Config::default()).expect("compiles");
    assert!(
        via_paren.diagnostics.is_empty(),
        "{:?}",
        via_paren.diagnostics
    );
    assert_eq!(
        base_decl(&via_paren, Prop::Background),
        base_decl(
            &compile_theme("bg-primary", &table, &Config::default()).expect("compiles"),
            Prop::Background
        ),
    );
}

