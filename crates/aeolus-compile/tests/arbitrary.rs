fn cn_merges_arbitrary_values_rightmost_wins() {
    let base = compile("w-[32px]", &Config::default()).expect("compiles");
    let over = compile("w-[40rem]", &Config::default()).expect("compiles");
    let merged = aeolus_compile::cn(&[&base, &over]).expect("merges");
    assert!(merged.diagnostics.is_empty());
    assert_eq!(base_decl(&merged, Prop::Width), Val::Rem(40.0));
}

#[test]
fn the_interpreter_resolves_arbitrary_decls_without_a_theme() {
    // Px/Rem/Pct/Num/Rgba are CONCRETE values — the theme-less interp
    // resolves them (no ThemeRequired boundary for arbitrary values).
    let compiled = compile("p-[1.5rem] w-[32px]", &Config::default()).expect("compiles");
    let resolved = interp(&compiled.program, &aeolus_compile::Env::default()).expect("resolves");
    assert!(resolved.notes.is_empty());
    assert_eq!(resolved.touched().len(), 5, "four paddings + the width");
}

#[test]
fn the_static_form_carries_the_arbitrary_values() {
    let compiled = compile("w-[32px]", &Config::default()).expect("compiles");
    let text = emit_static(&compiled.program);
    assert!(
        text.contains("aeolus_ir::Val::Px(32.0)"),
        "whole floats keep `.0`: {text}"
    );
}

#[test]
fn the_grammar_is_deterministic() {
    let a = compile(
        "p-[1.5rem] w-[32px] bg-[#0ea5e9] rotate-[45deg]",
        &Config::default(),
    )
    .expect("compiles");
    let b = compile(
        "p-[1.5rem] w-[32px] bg-[#0ea5e9] rotate-[45deg]",
        &Config::default(),
    )
    .expect("compiles");
    assert_eq!(a.program.layers.len(), b.program.layers.len());
    for (la, lb) in a.program.layers.iter().zip(b.program.layers.iter()) {
        assert_eq!(la.decls, lb.decls, "same input, same declarations");
    }
}
