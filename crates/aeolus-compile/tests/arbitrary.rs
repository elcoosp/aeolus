//! The arbitrary-value unit grammar's contracts (architecture plan §3.1's
//! value pass — the named remaining P2 slice until this battery): the
//! registry rows already ACCEPT the bracket/paren shape (`w-[32px]` lexes
//! body `w` plus a typed `Arb` group), and this suite pins the grammar
//! that finally LOWERS it — units, type hints, colours, var() token
//! references — and the typed boundaries that stay refused.
//!
//! The pins:
//!
//! * lengths lower onto the row's longhand fan-out (`w-[32px]` →
//!   `Val::Px(32.0)` on `Width`; `pl-[7px]` → `PaddingLeft` — the golden
//!   corpus's own classes, real-compiler ground truth);
//! * rem/percentage/number lower into the IR's own slots (`p-[1.5rem]` →
//!   `Rem`, `w-[50%]` → `Pct`, `opacity-[0.37]` → `Num` — the v4
//!   verbatim-passthrough reading);
//! * the sibling-row disambiguation is SILENT on the rows that never
//!   matched (`text-[13px]` lowers the font-size row only — NO
//!   line-height, NO colour-row noise; `text-[#0f0f0f]` the reverse);
//! * type hints constrain the parse (`length:`/`percentage:`/`number:`/
//!   `color:`; a mismatched hint is a typed refusal);
//! * colours parse through the audited `aeolus_core::Color` (hex →
//!   `Rgba`), and the `/opacity` modifier rides via the audited
//!   premultiplied bake;
//! * `var(…)`/`(--var)` references resolve through the theme pass's
//!   `TokenTable` when supplied — and refuse typed when not (the
//!   theme-less default);
//! * the CSS arm renders the same resolution (`padding-left: 7px`,
//!   hex verbatim, `1.5rem`) and the two walks' diagnostics stay EQUAL
//!   over the battery;
//! * the boundaries stay typed, coded and helped: bare values without a
//!   unit on non-`Number` rows, mismatched hints, the arbitrary-PROPERTY
//!   form, multi-token composites (`calc()`, underscore joins), angle
//!   units outside the `Deg` rows, keyword values on row-relative
//!   keyword slots.

