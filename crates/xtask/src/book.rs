//! The docs book's seam (plan §8's P5 row and §5.8's governance line —
//! the P5 phase's "docs book" deliverable): the single ordered reader
//! artifact over the docs the tree otherwise carries as scattered pages.
//!
//! The plan line this module delivers — `docs/AEOLUS_V1_ARCHITECTURE.md`
//! §8, the P5 row:
//!
//! > gpui-rsx integration PR, LSP/CLI (…), gpui-component bridge, **docs
//! > book**, public benchmarks, `1.0-rc`
//!
//! and §5.8's governance line ("…, docs book, migration guide, …").
//!
//! The book lands in the driver's own shape — two halves, one gate:
//!
//! * **The generated chapters** ride the `GeneratedArtifact` trait the
//!   other committed artifacts follow. Today one: the CLI reference,
//!   rendered verbatim from `aeolus_cli::USAGE` (the crate's own help
//!   text — the page is the binary's words, never a parallel claim,
//!   the conformance pages' publish-the-emitter's-verdicts rule).
//!   `cargo xtask gen-book` writes them; the byte drift is pinned in
//!   `crates/xtask/tests/book.rs` (plain `cargo test`, no driver needed).
//! * **The structural contract** is the whole-book walk
//!   ([`verify_book`]): every `docs/book/src/SUMMARY.md` entry resolves
//!   to a chapter file, every `{{#include}}` target exists (mdbook
//!   resolves them at build time — a moved page would break the build),
//!   and `book.toml` carries the `[book]` table with the `title`/`src`
//!   keys the build needs. A hand-authored chapter cannot drift from
//!   the registry this way: the big generated pages (REGISTRY,
//!   CONFORMANCE, MIGRATION) are included, never copied.
//!
//! The exit-code contract is the driver's own: `0` clean/written, `1`
//! drift or structural break, `2` usage error.

use std::fmt::Write as _;
use std::path::Path;

use aeolus_data::codegen::GeneratedArtifact;

/// The book's workspace-relative directory (the `--root` walk joins it).
const BOOK_DIR: &str = "docs/book";

/// The generated CLI-reference chapter (`docs/book/src/cli-reference.md`):
/// the headless surface's own `USAGE` text, rendered into the book's
/// reference part. GENERATED — the committed bytes are the crate's own
/// help text, pinned by `verify-book` and the `tests/book.rs` battery.
struct CliReferenceDocs;

impl GeneratedArtifact for CliReferenceDocs {
    fn name(&self) -> &'static str {
        "book-cli-reference"
    }

    fn path(&self) -> &'static str {
        "docs/book/src/cli-reference.md"
    }

    fn generate(&self) -> String {
        // The `USAGE` value carries real newlines; the fence is a plain
        // ```text block (the usage text never contains a fence — the
        // battery's content pin proves it).
        format!(
            "<!-- GENERATED by `cargo xtask gen-book` from \
`aeolus_cli::USAGE` (the CLI crate's own help text) — DO NOT EDIT. \
The committed bytes are pinned by `cargo xtask verify-book` and the \
drift battery in `crates/xtask/tests/book.rs`; a usage-text edit that \
forgets the regeneration fails the gate. -->\n\n\
# CLI reference\n\n\
The headless surface's own help text, rendered verbatim from the \
`aeolus-cli` crate's `USAGE` — the single source: the page regenerates \
from the crate, so the book can never drift from the binary's \
`--help`. The theme spec, the fail-on modes and the exit-code contract \
are the text's own sections.\n\n\
```text\n{}\n```\n",
            aeolus_cli::USAGE
        )
    }
}

/// The book's generated-chapter list — the `gen-book`/`verify-book`
/// commands' artifact family (the generated chapters; the hand-authored
/// chapters are the authors', the structure walk covers them).
pub fn artifacts() -> Vec<&'static dyn GeneratedArtifact> {
    vec![&CliReferenceDocs]
}

/// One structure-check outcome: the check's name, the workspace-relative
/// path it ran over, and the verdict line (`clean` when fine, the
/// problem's own description otherwise — the report the operator reads).
struct StructureCheck {
    name: &'static str,
    path: String,
    verdict: String,
}

impl StructureCheck {
    fn clean(name: &'static str, path: &str) -> Self {
        Self {
            name,
            path: path.to_string(),
            verdict: "clean".to_string(),
        }
    }

    fn broken(name: &'static str, path: &str, verdict: String) -> Self {
        Self {
            name,
            path: path.to_string(),
            verdict,
        }
    }

    fn report(&self) -> String {
        format!("{}  {}  {}\n", self.name, self.path, self.verdict)
    }
}

/// The whole-book structural walk: `book.toml`'s `[book]` table, the
/// `SUMMARY.md` entries, every chapter's `{{#include}}` targets. Returns
/// one check per walked surface — `clean` verdicts and breakages alike —
/// so the report is the book's full inventory, not just its failures.
fn structure_checks(root: &Path) -> Vec<StructureCheck> {
    let book = root.join(BOOK_DIR);
    let src = book.join("src");
    let mut checks = Vec::new();

    // --- book.toml: the [book] table with the keys the build needs ---
    let config_path = book.join("book.toml");
    match std::fs::read_to_string(&config_path) {
        Ok(text) => {
            let mut in_book = false;
            let mut title = false;
            let mut src_key = false;
            for line in text.lines() {
                let trimmed = line.trim();
                if trimmed.starts_with('[') && trimmed.ends_with(']') {
                    in_book = trimmed == "[book]";
                    continue;
                }
                if in_book {
                    if trimmed.starts_with("title") {
                        title = true;
                    }
                    if trimmed.starts_with("src") {
                        src_key = true;
                    }
                }
            }
            if title && src_key {
                checks.push(StructureCheck::clean(
                    "book-config",
                    &format!("{BOOK_DIR}/book.toml"),
                ));
            } else {
                let missing = if title { "src" } else { "title" };
                checks.push(StructureCheck::broken(
                    "book-config",
                    &format!("{BOOK_DIR}/book.toml"),
                    format!("INVALID — the [book] table is missing its `{missing}` key (the mdbook build needs both)"),
                ));
            }
        }
        Err(_) => checks.push(StructureCheck::broken(
            "book-config",
            &format!("{BOOK_DIR}/book.toml"),
            "MISSING — run: create the book's `book.toml`".to_string(),
        )),
    }

    // --- SUMMARY.md: every entry resolves to a chapter file ---
    let summary_path = src.join("SUMMARY.md");
    let summary = std::fs::read_to_string(&summary_path);
    let entries = summary.as_deref().map(summary_entries).unwrap_or_default();
    if summary.is_err() {
        checks.push(StructureCheck::broken(
            "book-structure",
            &format!("{BOOK_DIR}/src/SUMMARY.md"),
            "MISSING — the book has no table of contents".to_string(),
        ));
    } else if entries.is_empty() {
        checks.push(StructureCheck::broken(
            "book-structure",
            &format!("{BOOK_DIR}/src/SUMMARY.md"),
            "EMPTY — the table of contents names no chapter".to_string(),
        ));
    } else {
        let mut broken = String::new();
        let mut count = 0usize;
        for (title, path) in &entries {
            if !src.join(path).is_file() {
                let _ = write!(
                    broken,
                    "entry {title:?} points at the missing chapter file {path}; ",
                );
                count += 1;
            }
        }
        if count == 0 {
            checks.push(StructureCheck::clean(
                "book-structure",
                &format!("{BOOK_DIR}/src/SUMMARY.md"),
            ));
        } else {
            checks.push(StructureCheck::broken(
                "book-structure",
                &format!("{BOOK_DIR}/src/SUMMARY.md"),
                format!(
                    "MISSING — {count} entr{} unresolved: {}",
                    if count == 1 { "y" } else { "ies" },
                    broken,
                ),
            ));
        }
    }

    // --- the chapters: every {{#include}} target exists ---
    let mut chapter_files: Vec<std::path::PathBuf> = Vec::new();
    if let Ok(read_dir) = std::fs::read_dir(&src) {
        for entry in read_dir.flatten() {
            let path = entry.path();
            if path.extension().is_some_and(|e| e == "md") {
                chapter_files.push(path);
            }
        }
    }
    chapter_files.sort();
    let mut include_broken = String::new();
    let mut include_count = 0usize;
    for chapter in &chapter_files {
        let Ok(text) = std::fs::read_to_string(chapter) else {
            continue;
        };
        for target in include_targets(&text) {
            include_count += 1;
            let resolved = chapter.parent().unwrap_or(Path::new(".")).join(&target);
            if !resolved.is_file() {
                let name = chapter
                    .file_name()
                    .and_then(|n| n.to_str())
                    .unwrap_or_default();
                let _ = write!(
                    include_broken,
                    "{name} includes the missing file {target}; ",
                );
            }
        }
    }
    if include_broken.is_empty() {
        checks.push(StructureCheck::clean(
            "book-includes",
            &format!(
                "{BOOK_DIR}/src ({} include{})",
                include_count,
                if include_count == 1 { "" } else { "s" }
            ),
        ));
    } else {
        checks.push(StructureCheck::broken(
            "book-includes",
            &format!("{BOOK_DIR}/src"),
            format!("MISSING — the broken include targets: {include_broken}"),
        ));
    }

    checks
}

/// The `(title, path)` pairs a `SUMMARY.md` names — the `- [Title](path)`
/// lines (mdbook's list form; part headers are `#` lines, external links
/// start with a scheme and are skipped).
fn summary_entries(summary: &str) -> Vec<(String, String)> {
    let mut entries = Vec::new();
    for line in summary.lines() {
        let trimmed = line.trim_start();
        let Some(rest) = trimmed
            .strip_prefix("- [")
            .or_else(|| trimmed.strip_prefix("  - ["))
        else {
            continue;
        };
        let Some((title, after)) = rest.split_once("](") else {
            continue;
        };
        let Some((path, _)) = after.split_once(')') else {
            continue;
        };
        if path.starts_with("http://") || path.starts_with("https://") {
            continue;
        }
        entries.push((title.trim().to_string(), path.trim().to_string()));
    }
    entries
}

/// The `{{#include TARGET}}` directives one chapter carries — the raw
/// target text, resolved by mdbook relative to the chapter file.
fn include_targets(chapter: &str) -> Vec<String> {
    let mut targets = Vec::new();
    let mut rest = chapter;
    while let Some(start) = rest.find("{{#include") {
        let after = &rest[start + "{{#include".len()..];
        let Some(end) = after.find("}}") else {
            break;
        };
        let target = after[..end].trim();
        if !target.is_empty() {
            targets.push(target.to_string());
        }
        rest = &after[end + 2..];
    }
    targets
}

/// `cargo xtask gen-book` — write the generated chapters (write mode
/// over [`artifacts`], the focused walk's own contract). `--check` is
/// the verify behaviour's alias (the `gen-tables --check` spelling).
pub fn gen_book(root: &Path, check: bool, out: &mut dyn std::io::Write) -> i32 {
    if check {
        return verify(root, out);
    }
    let mut exit = crate::EXIT_OK;
    let mut report = String::new();
    for artifact in artifacts() {
        let (artifact_exit, artifact_report) = crate::walk_one(root, false, artifact);
        exit = exit.max(artifact_exit);
        report.push_str(&artifact_report);
    }
    let _ = out.write_all(report.as_bytes());
    exit
}

/// `cargo xtask verify-book` — the whole gate: the generated chapters'
/// byte drift (verify mode over [`artifacts`]) AND the structural walk
/// ([`structure_checks`]). Exit 1 on ANY failure; the report is the
/// full inventory either way.
pub fn verify(root: &Path, out: &mut dyn std::io::Write) -> i32 {
    let mut exit = crate::EXIT_OK;
    let mut report = String::new();
    for artifact in artifacts() {
        let (artifact_exit, artifact_report) = crate::walk_one(root, true, artifact);
        exit = exit.max(artifact_exit);
        report.push_str(&artifact_report);
    }
    for check in structure_checks(root) {
        if check.verdict != "clean" {
            exit = exit.max(crate::EXIT_DRIFT);
        }
        report.push_str(&check.report());
    }
    let _ = out.write_all(report.as_bytes());
    exit
}
